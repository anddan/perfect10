export const TABLES: Record<Lang, Table> = {sv, en, es, it};

/** Each language's name in itself: the same whatever language is on. */
export const LANG_NAMES: Record<Lang, string> = {sv: "Svenska", en: "English", es: "Español", it: "Italiano"};

const STORAGE_KEY = "p10-lang";

/** The language the person last chose, otherwise the one the browser is in (if it is one of the four), otherwise English. */
function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && (LANGS as string[]).includes(saved)) return saved as Lang;
  } catch {
    /* private mode, or no browser */
  }
  const browser = typeof navigator !== "undefined" && navigator.language ? navigator.language.slice(0, 2).toLowerCase() : "en";
  return (LANGS as string[]).includes(browser) ? (browser as Lang) : "en";
}

let current: Lang = detect();

export function lang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  current = l;
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* private mode */
  }
  if (typeof document !== "undefined") document.documentElement.lang = l;
}

/** The language after this one in the list: the language button goes round them. */
export function nextLang(): Lang {
  return LANGS[(LANGS.indexOf(current) + 1) % LANGS.length];
}

/** A text in the language that is on. `{n}` and `{m}` in it are filled in from `vars`. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = TABLES[current][key];
  return vars ? s.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? "")) : s;
}
